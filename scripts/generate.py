def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='Fail on missing, stale or orphaned generated files without writing.')
    args=parser.parse_args()
    output=render(load(),load(SCHEMA))
    stale=[]
    for name,text in output.items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != text:stale.append(name)
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text,encoding='utf-8')
    orphaned=[str(p.relative_to(ROOT)) for p in (ROOT/'categories').glob('*.md') if str(p.relative_to(ROOT)) not in output]
    stale+=orphaned
    if stale:
        print('Regenerate with python scripts/generate.py; stale/orphaned files: '+', '.join(stale),file=sys.stderr);return 1
    print(f'{"Checked" if args.check else "Generated"} {len(output)} Markdown views.')
    return 0


if __name__=='__main__':sys.exit(main())
